export const git = Effect.fnUntraced(function* (
  cwd: string,
  ...args: ReadonlyArray<string>
) {
  const spawner = yield* ChildProcessSpawner.ChildProcessSpawner
  return String.trim(
    yield* spawner.string(ChildProcess.make('git', args, { cwd }))
  )
})

export const workspace = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem
  const path = yield* Path.Path
  const root = yield* fs.makeTempDirectoryScoped()

  yield* Effect.forEach(
    Record.toEntries(files),
    Effect.fnUntraced(function* ([file, content]) {
      yield* fs.makeDirectory(path.dirname(path.join(root, file)), {
        recursive: true,
      })
      yield* fs.writeFileString(path.join(root, file), content)
    })
  )
  // pnpm links workspace packages the same way
  yield* fs.makeDirectory(path.join(root, 'packages/app/node_modules/@ws'), {
    recursive: true,
  })
  yield* fs.symlink(
    '../../../lib',
    path.join(root, 'packages/app/node_modules/@ws/lib')
  )
  yield* git(root, 'init', '--quiet')
  yield* git(root, 'config', 'user.email', 'test@example.com')
  yield* git(root, 'config', 'user.name', 'Test')
  yield* git(root, 'add', '.')
  yield* git(root, 'commit', '--quiet', '-m', 'init')
  return { root, commit: yield* git(root, 'rev-parse', 'HEAD') }
})

const spawn = Effect.fnUntraced(function* (
  cwd: string,
  args: ReadonlyArray<string>
) {
  const spawner = yield* ChildProcessSpawner.ChildProcessSpawner
  const path = yield* Path.Path
  return yield* spawner.spawn(
    ChildProcess.make(
      'node',
      [path.join(import.meta.dirname, '../src/index.ts'), ...args],
      {
        cwd,
        env: { ATLAS_VIEWER: path.join(import.meta.dirname, 'viewer') },
        extendEnv: true,
      }
    )
  )
})

export const atlas = Effect.fnUntraced(function* (
  cwd: string,
  ...args: ReadonlyArray<string>
) {
  const handle = yield* spawn(cwd, args)
  const [stdout, stderr, exitCode] = yield* Effect.all(
    [
      Stream.mkString(Stream.decodeText(handle.stdout)),
      Stream.mkString(Stream.decodeText(handle.stderr)),
      handle.exitCode,
    ],
    { concurrency: 'unbounded' }
  )
  return { stdout, stderr, exitCode }
}, Effect.scoped)

export const serve = Effect.fnUntraced(function* (
  cwd: string,
  ...args: ReadonlyArray<string>
) {
  const handle = yield* spawn(cwd, ['serve', '--no-open', ...args])
  const url = yield* handle.stderr.pipe(
    Stream.decodeText,
    Stream.splitLines,
    Stream.filterMap(
      Filter.fromPredicateOption((line: string) =>
        pipe(
          line,
          String.match(/ at (http:\/\/\S+)$/),
          Option.flatMap((match) => Option.fromNullishOr(match[1]))
        )
      )
    ),
    Stream.runHead
  )
  return yield* Option.match(url, {
    onNone: () => Effect.die('atlas serve stopped before it printed its URL'),
    onSome: Effect.succeed,
  })
})
